#!/usr/bin/env python3
"""Regenerate the template-grade LUTs in this directory.

Each grade is a small, documented RGB transform sampled onto a 16^3
lattice and written as an Adobe .cube file. The transforms are
MotionWren originals: no bought LUT, no copied look is used anywhere.

Usage: python3 generate-luts.py
Writes: bright-warm-day.cube, night-warm-windows.cube,
        warm-evening-interior.cube (LUT_3D_SIZE 16, 4 decimals).
"""

import math
import os

SIZE = 16
HERE = os.path.dirname(os.path.abspath(__file__))


def clamp(v):
    return min(1.0, max(0.0, v))


def saturate(r, g, b, amount):
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    return (luma + (r - luma) * amount,
            luma + (g - luma) * amount,
            luma + (b - luma) * amount)


def bright_warm_day(r, g, b):
    # Bright day, warm sun, saturated blue sky: a touch more saturation,
    # red lifted and blue pulled back (warm), a small overall lift.
    r, g, b = saturate(r, g, b, 1.06)
    r = r * 1.05 + 0.008
    g = g * 1.01 + 0.008
    b = b * 0.94 + 0.008
    return clamp(r), clamp(g), clamp(b)


def night_warm_windows(r, g, b):
    # Dark blue night sky, warm lit windows: darken hard, push the
    # shadows blue, let the highlights stay warm.
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    r = r * 0.66 + 0.05 * luma * luma
    g = g * 0.66 + 0.02 * luma * luma
    b = b * 0.66 + 0.06 * (1.0 - luma) * (1.0 - luma)
    return clamp(r), clamp(g), clamp(b)


def warm_evening_interior(r, g, b):
    # Warm evening interior light: warm the midtones, a small lift,
    # a touch more saturation.
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    w = math.sin(math.pi * luma)  # 0 in the blacks/whites, 1 in the mids
    r = r + 0.045 * w
    g = g + 0.005 * w
    b = b - 0.035 * w
    r, g, b = saturate(r, g, b, 1.04)
    return clamp(r * 1.01 + 0.008), clamp(g * 1.01 + 0.008), clamp(b * 1.01 + 0.008)


GRADES = {
    "bright-warm-day": bright_warm_day,
    "night-warm-windows": night_warm_windows,
    "warm-evening-interior": warm_evening_interior,
}


def write_lut(name, fn):
    path = os.path.join(HERE, f"{name}.cube")
    lines = [
        f'TITLE "{name}"',
        "# MotionWren template grade. Generated by generate-luts.py — edit the transform there, not this file.",
        "LUT_3D_SIZE 16",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
        "",
    ]
    for b in range(SIZE):
        for g in range(SIZE):
            for r in range(SIZE):
                x, y, z = (r / (SIZE - 1), g / (SIZE - 1), b / (SIZE - 1))
                out = fn(x, y, z)
                lines.append(f"{out[0]:.4f} {out[1]:.4f} {out[2]:.4f}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path} ({len(lines)} lines)")


if __name__ == "__main__":
    for name, fn in GRADES.items():
        write_lut(name, fn)
