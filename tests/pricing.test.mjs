import { build } from "esbuild";
const out = await build({ entryPoints: ["app/pricing.ts"], bundle: true, format: "esm", write: false });
const mod = await import("data:text/javascript;base64," + Buffer.from(out.outputFiles[0].text).toString("base64"));
let failed = 0;
const check = (name, ok, detail = "") => { console.log(`${ok ? "PASS" : "FAIL"} ${name}${ok ? "" : " " + detail}`); if (!ok) failed++; };
const { priceForSeconds, autoQuote, quoteFor, upgradeCents, priceForScenes } = mod;
check("20 s is $29", priceForSeconds(20) === 2900);
check("30 s is $39", priceForSeconds(30) === 3900);
check("60 s is $59", priceForSeconds(60) === 5900);
check("10 s is still $29 (never below the base)", priceForSeconds(10) === 2900);
check("auto: 1 to 4 photos are $29", [1, 2, 3, 4].every((n) => autoQuote(n).cents === 2900));
check("auto: 5 photos $34, 6 photos $39", autoQuote(5).cents === 3400 && autoQuote(6).cents === 3900);
check("auto: 7..12 photos step toward $59", [7, 8, 9, 10, 11, 12].map((n) => priceForScenes(n)).join() === "4200,4600,4900,5200,5600,5900");
check("auto: past 12 adds $5 a photo", autoQuote(13).cents === 6400 && autoQuote(15).cents === 7400);
check("auto: length is 5 s a photo, at least 20 s", autoQuote(3).seconds === 20 && autoQuote(9).seconds === 45 && autoQuote(13).seconds === 65);
check("auto: capped at 24 photos", autoQuote(40).scenes === 24 && autoQuote(40).cents === 5900 + 500 * 12);
check("price never goes down as photos are added", Array.from({ length: 24 }, (_, i) => priceForScenes(i + 1)).every((v, i, a) => i === 0 || v >= a[i - 1]));
check("fixed 0 means automatic", quoteFor(0, 7).cents === 4200 && quoteFor(30, 99).cents === 3900);
check("upgrade is the part above the credit", upgradeCents(2900) === 0 && upgradeCents(3900) === 1000 && upgradeCents(5900) === 3000);
console.log(failed ? `${failed} failed` : "all passed");
process.exit(failed ? 1 : 0);
